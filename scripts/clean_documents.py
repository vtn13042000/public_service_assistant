"""The "làm sạch" step for non-procedure documents (ROUND-4-DATA.md, processing steps 2–5).

Usage: uv run python scripts/clean_documents.py [--in data/processed_docs] [--out data/clean_docs] [--sources DIR...]
Reads <in>/<kind>/*.json, writes cleaned copies to <out>/<kind>/ (the out dir is replaced) and <out>/CLEAN_REPORT.md.
Per document, in order:
  1. schema + kind/directory check (invalid -> skipped);
  2. Unicode NFC, HTML entities/tags, zero-width and non-breaking spaces, whitespace per line, blank-line runs;
  3. boilerplate: navigation/share/copyright/cookie lines, lines repeated across >= 50% (and >= 4) of one site's
     non-legal documents (headers/footers), and the "Tin liên quan …" tail;
  4. legal_text: a section holding further "Điều N." lines is split into one section per article;
  5. near-empty text (< 20 letters; scanned PDF, no OCR) -> skipped;
  6. link validation: procedure_ids not in the procedure records are removed; none left -> skipped;
  7. de-duplication by doc_id, cleaned text (text_sha256, written to the output) and (kind, title): the first file
     in sorted path order is kept. The raw-file sha256 is provenance only (articles of one law share it).
Content is otherwise kept verbatim; each output file lists its `cleaning_actions`.
"""
import argparse
import json
import shutil
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src.db import DEFAULT_PREFER  # noqa: E402
from src.documents import DOC_KINDS, clean_corpus, procedure_ids_from, read_documents  # noqa: E402


def _kind(action: str) -> str:
    a = action.split(": ", 1)[-1]
    for key in ("tail cut", "boilerplate", "repeated site line", "resegmented", "dropped", "unknown procedure_ids",
                "timestamp"):
        if key in action:
            return key
    return a.split(" ")[0]


def report(kept, skipped, docs, args) -> str:
    by_in = Counter(d.kind_dir or "(none)" for d in docs)
    by_out = Counter(data["kind"] for _, data in kept)
    by_skip = Counter(d.kind_dir or "(none)" for d in skipped)
    acts = Counter(_kind(a) for d, _ in kept for a in d.actions)
    n_sec = sum(len(data["sections"]) for _, data in kept)
    L = ["# CLEAN_REPORT — non-procedure documents", "",
         f"Input `{args.inp}`, output `{args.out}`, procedure records {', '.join(f'`{s}`' for s in args.sources)}. "
         "Generated by `scripts/clean_documents.py`; do not edit by hand.", "",
         f"**{len(docs)} files in, {len(kept)} documents kept ({n_sec} sections), {len(skipped)} skipped.**", "",
         "| kind | in | kept | skipped | sections kept |", "|---|---|---|---|---|"]
    for k in [*DOC_KINDS, *sorted(set(by_in) - set(DOC_KINDS))]:
        if by_in[k] or by_out[k]:
            secs = sum(len(data["sections"]) for _, data in kept if data["kind"] == k)
            L.append(f"| {k} | {by_in[k]} | {by_out[k]} | {by_skip[k]} | {secs} |")
    L += ["", "## Cleaning actions (kept documents)", "", "| action | count |", "|---|---|"]
    L += [f"| {a} | {n} |" for a, n in acts.most_common()] or ["| (none) | 0 |"]
    L += ["", "## Skipped", ""]
    L += [f"- `{d.path}`: {'; '.join(d.errors)}" for d in skipped] or ["(none)"]
    L += ["", "## Per document", "", "| file | doc_id | kind | procedures | sections | actions |", "|---|---|---|---|---|---|"]
    for d, data in kept:
        a = "; ".join(d.actions) or "—"
        L.append(f"| `{d.path.relative_to(args.inp)}` | `{data['doc_id']}` | {data['kind']} | "
                 f"{', '.join(data['procedure_ids'])} | {len(data['sections'])} | {a.replace('|', '/')[:400]} |")
    return "\n".join(L) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--in", dest="inp", default="data/processed_docs")
    ap.add_argument("--out", default="data/clean_docs")
    ap.add_argument("--sources", nargs="+", default=[f"data/processed/{n}" for n in DEFAULT_PREFER])
    args = ap.parse_args(argv)
    inp, out = Path(args.inp), Path(args.out)
    if not inp.is_dir():
        print(f"not a directory: {inp}", file=sys.stderr)
        return 2
    if out.resolve() == inp.resolve():
        print("--out must differ from --in (inputs are never modified)", file=sys.stderr)
        return 2
    docs = read_documents(inp)
    kept, skipped = clean_corpus(docs, procedure_ids_from(args.sources))
    if out.exists():
        shutil.rmtree(out)
    for d, data in kept:
        p = out / data["kind"] / d.path.name
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    out.mkdir(parents=True, exist_ok=True)
    (out / "CLEAN_REPORT.md").write_text(report(kept, skipped, docs, args), encoding="utf-8")
    print(f"{len(docs)} in, {len(kept)} kept, {len(skipped)} skipped -> {out}/ (report {out}/CLEAN_REPORT.md)")
    for d in skipped:
        print(f"  SKIP {d.path}: {'; '.join(d.errors)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
